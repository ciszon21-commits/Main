def get_plant_name(unit_name):
    """
    從機組名稱提取電廠名稱。
    例如：'大潭CC#1' → '大潭', '林口#1' → '林口'
    """
    # 嘗試完全匹配
    if unit_name in PLANT_COORDINATES:
        return unit_name

    # 嘗試去除常見後綴
    import re
    # 去除 CC#N, GT#N, #N, Gas#N, (註N) 等
    clean = re.sub(r'(CC|GT|Gas|新CC)?#\d+.*$', '', unit_name)
    clean = re.sub(r'\(註\d+\)$', '', clean).strip()

    if clean in PLANT_COORDINATES:
        return clean

    # 嘗試逐字縮短匹配
    for length in range(len(unit_name), 1, -1):
        prefix = unit_name[:length]
        if prefix in PLANT_COORDINATES:
            return prefix

    return None


def get_coordinates(unit_name):
    """
    根據機組名稱取得經緯度座標。
    回傳 (lat, lng) 或 None
    """
    plant = get_plant_name(unit_name)
    if plant:
        return PLANT_COORDINATES[plant]
    return None
