def interpolate(i,input_x,x_list,y_list):
    x=input_x
    x1=x_list[i-1]
    y1=y_list[i-1]
    x2=x_list[i]
    y2=y_list[i]
    m=(y2-y1)/(x2-x1)
    y=(x-x1)*m+y1
    return y 
