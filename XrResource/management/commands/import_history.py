    def add_arguments(self, parser):
        parser.add_argument(
            '--check',
            action='store_true',
            help='僅檢查資料結構，不執行匯入',
        )
        parser.add_argument(
            '--dry-run',
            action='store_true',
            help='預覽轉換後的資料，不寫入資料庫',
        )
        parser.add_argument(
            '--import',
            action='store_true',
            help='執行正式匯入',
        )

    def parse_date(self, date_val):
        """解析日期，如果只有年份則預設為該年 1 月 1 日"""
        if date_val is None or date_val == '-':
            return None
        
        if isinstance(date_val, int) or (isinstance(date_val, str) and len(date_val) == 4 and date_val.isdigit()):
            return datetime.date(int(date_val), 1, 1)
        
        if isinstance(date_val, str):
            # 處理 2021-12-28T00:00:00 格式
            try:
                dt = datetime.datetime.fromisoformat(date_val)
                return dt.date()
            except ValueError:
                return None
        return None

    def handle(self, *args, **options):
        data_list = self.DATA.get('工作表1', [])
        
        if options['check']:
            self.stdout.write(self.style.SUCCESS(f"成功加載資料，共 {len(data_list)} 筆紀錄"))
            return

        mapped_records = []
        for idx, item in enumerate(data_list):
            # 依照規則對應
            record = {
                'activity_name': item.get('原因') or '未填寫',
                'nature_str': item.get('性質'),
                'activity_date': self.parse_date(item.get('日期')),
                'reason': item.get('備註') or '',
                'department': item.get('租借部門') or '未知部門',
                'borrower_name': item.get('租借人') or '未知',
                'borrower_id': '',  # 暫時從缺
                'rental_start': self.parse_date(item.get('租借日期')),
                'rental_end': self.parse_date(item.get('歸還日期')),
                'equipment_sns': [sn.strip() for sn in str(item.get('設備編號') or '').split('\n') if sn.strip() and sn != '-'],
            }
            # 補齊必填日期 (若租借日缺失則用活動日)
            if not record['rental_start']: record['rental_start'] = record['activity_date']
            if not record['rental_end']: record['rental_end'] = record['rental_start']
            if not record['activity_date']: record['activity_date'] = record['rental_start']
            
            mapped_records.append(record)

        if options['dry_run']:
            self.stdout.write(self.style.SUCCESS(f"--- 預覽轉換後的資料 (前 3 筆) ---"))
            for r in mapped_records[:3]:
                self.stdout.write(json.dumps(r, ensure_ascii=False, indent=4, default=str))
            self.stdout.write(f"... 共 {len(mapped_records)} 筆紀錄")
            return

        if not options['import']:
            self.stdout.write(self.style.WARNING("請使用 --dry-run 預覽或 --import 執行匯入。"))
            return

        # 執行正式匯入
        self.stdout.write(self.style.SUCCESS(f"開始匯入 {len(mapped_records)} 筆紀錄..."))
        import_count = 0
        
        for r in mapped_records:
            try:
                # 處理性質 (RentalNature)
                nature_obj = None
                if r['nature_str']:
                    nature_obj, _ = RentalNature.objects.get_or_create(name=r['nature_str'])

                # 建立租借紀錄
                rental = XrRentalRecord.objects.create(
                    activity_date=r['activity_date'],
                    rental_start=r['rental_start'],
                    rental_end=r['rental_end'],
                    department=r['department'],
                    borrower_name=r['borrower_name'],
                    borrower_id=r['borrower_id'],
                    activity_name=r['activity_name'],
                    reason=r['reason'],
                    nature=nature_obj,
                    status='returned'  # 歷史資料預設為已歸還
                )

                # 處理設備關聯
                for sn in r['equipment_sns']:
                    equip = XrEquipment.objects.filter(serial_number=sn).first()
                    if equip:
                        rental.equipments.add(equip)
                    else:
                        self.stdout.write(self.style.WARNING(f"  [跳過設備] 找不到序號: {sn} (紀錄: {r['activity_name']})"))
                
                import_count += 1
            except Exception as e:
                self.stdout.write(self.style.ERROR(f"  [匯入失敗] {r['activity_name']}: {str(e)}"))

        self.stdout.write(self.style.SUCCESS(f"匯入完成！成功匯入 {import_count} 筆紀錄。"))
